function SectionCard({ title, badge, icon, children }: { title: string; badge?: string; icon: string; children: ReactNode }) {
  return (
    <section className="card" style={{ marginBottom: 16 }}>
      <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: 12, flexWrap: 'wrap', gap: 8 }}>
        <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
          <span style={{ fontSize: 18 }}>{icon}</span>
          <h2 style={{ margin: 0, fontSize: 16.5 }}>{title}</h2>
        </div>
        {badge && (
          <span className="badge" style={{ fontSize: 11 }}>
            {badge}
          </span>
        )}
      </div>
      {children}
    </section>
  )
}

function P({ children }: { children: ReactNode }) {
  return <p style={{ margin: '5px 0', fontSize: 13.5, lineHeight: 1.6, color: '#cbd5e1' }}>{children}</p>
}

function K({ children }: { children: ReactNode }) {
  return (
    <code style={{ background: '#1c2230', border: '1px solid #28334a', borderRadius: 4, padding: '1px 6px', fontSize: 12.5, color: '#38bdf8', fontFamily: 'Consolas, monospace' }}>
      {children}
    </code>
  )
}

function FeatureList({ items }: { items: { name: string; desc: ReactNode }[] }) {
  return (
    <ul style={{ listStyle: 'none', padding: 0, margin: '8px 0' }}>
      {items.map((it, idx) => (
        <li
          key={idx}
          style={{
            padding: '8px 10px',
            borderRadius: 6,
            background: idx % 2 === 0 ? 'rgba(255, 255, 255, 0.02)' : 'transparent',
            display: 'flex',
            flexDirection: 'column',
            gap: 3,
            fontSize: 13.5,
            lineHeight: 1.5,
          }}
        >
          <span style={{ fontWeight: 600, color: '#f8fafc' }}>{it.name}</span>
          <span style={{ color: '#94a3b8' }}>{it.desc}</span>
        </li>
      ))}
    </ul>
  )
}

