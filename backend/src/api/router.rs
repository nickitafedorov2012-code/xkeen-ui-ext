use axum::routing::{any, delete, get, post, put};
use axum::Router;

use crate::{api, auth, updater, AppState};

pub fn api_router() -> Router<AppState> {
    Router::new()
        .merge(auth_routes())
        .merge(system_routes())
        .merge(servers_and_whitelist_routes())
        .merge(devices_and_routing_routes())
        .merge(config_and_backups_routes())
        .merge(failover_and_providers_routes())
        .merge(logs_and_updates_routes())
        .merge(diagnostics_and_features_routes())
        .merge(zapret_and_vkturn_routes())
        .merge(gaming_and_adguard_routes())
        // 404 JSON для несуществующих маршрутов API (вместо отдачи HTML через SPA fallback)
        .route("/api/{*path}", any(api::api_not_found))
}

fn auth_routes() -> Router<AppState> {
    Router::new()
        .route("/api/auth/status", get(auth::auth_status))
        .route("/api/auth/login", post(auth::login))
        .route("/api/auth/logout", post(auth::logout))
        .route("/api/auth/password", post(auth::change_password))
        .route("/api/auth/change-password", post(auth::change_password))
}

